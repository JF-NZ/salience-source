export const isRetiredSeedQuote = (value: Pick<Quote, 'id' | 'author' | 'isUserAdded'>) => {
  if (value.isUserAdded) {
    return false
  }

  const author = value.author.trim().toLowerCase()
  return retiredNonNeutralSeedQuoteIds.has(value.id)
    || author === 'salience'
    || author.includes('inspired')
    || author.endsWith(' theme')
}

